// Puente mínimo y seguro renderer <-> main
const { contextBridge, ipcRenderer } = require('electron');
const on = (ch) => (cb) => { const f = (_e, d) => cb(d); ipcRenderer.on(ch, f); return () => ipcRenderer.removeListener(ch, f); };
contextBridge.exposeInMainWorld('jarvis', {
  chat: (id, messages) => ipcRenderer.invoke('ai:chat', { id, messages }),
  onChunk: on('ai:chunk'),
  onStats: on('stats'),
  tool: (name, args) => ipcRenderer.invoke('tool:run', { name, args }),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (s) => ipcRenderer.invoke('settings:set', s),
  memAdd: (role, content) => ipcRenderer.invoke('mem:add', { role, content }),
  memClear: () => ipcRenderer.invoke('mem:clear'),
  onLevel: on('voice:level'),
  say: (text) => ipcRenderer.invoke('voice:say', text),
  stop: () => ipcRenderer.invoke('voice:stop'),
  onVoiceEvent: on('voice:event'),
  itemAdd: (kind, text) => ipcRenderer.invoke('item:add', { kind, text }),
  itemList: (kind) => ipcRenderer.invoke('item:list', kind),
  itemClear: (kind) => ipcRenderer.invoke('item:clear', kind),
  openApp: (id) => ipcRenderer.invoke('app:open', id),
  closeApp: (id) => ipcRenderer.invoke('app:close', id),
  cancelListen: () => ipcRenderer.invoke('voice:cancel'),
  onCommand: on('app:cmd'),
  convoState: (on) => ipcRenderer.send('app:convoState', on),
  notify: (p) => ipcRenderer.invoke('notify:send', p),
  whatsapp: (p) => ipcRenderer.invoke('whatsapp:send', p),
  toggleLoopback: (on) => ipcRenderer.invoke('voice:toggleLoopback', on),
  pc: (action, args) => ipcRenderer.invoke('pc:run', { action, args }),
  mobileInfo: () => ipcRenderer.invoke('mobile:info'),
  mobileHttps: () => ipcRenderer.invoke('mobile:https'),
  nova: (ch, d) => ipcRenderer.invoke('nova:' + ch, d),
  onNova: (ch, cb) => { if (!/^[a-z:-]+$/.test(ch)) return () => {}; const f = (_e, d) => cb(d); ipcRenderer.on('nova:' + ch, f); return () => ipcRenderer.removeListener('nova:' + ch, f); },
  memHistory: () => ipcRenderer.invoke('mem:history'),
  memSearch: (q) => ipcRenderer.invoke('mem:search', q),
  listen: () => ipcRenderer.invoke('voice:listen'),
  speak: (text) => ipcRenderer.invoke('voice:speak', text),
  resetVoice: () => ipcRenderer.invoke('voice:reset'),
  mediaCmd: (action) => ipcRenderer.invoke('system:media', action),
  screenshot: () => ipcRenderer.invoke('system:screenshot'),
  desktopWidgets: (action = 'toggle', options = {}) => ipcRenderer.invoke('desktop:widgets', { action, ...options }),
  desktopWidgetsInput: (ignore) => ipcRenderer.invoke('desktop:widgets-input', ignore === true),
  agent: {
    tools: () => ipcRenderer.invoke('agent:tools'),
    start: (tool, args, dryRun) => ipcRenderer.invoke('agent:start', { tool, args, dryRun }),
    run: (tool, args, dryRun) => ipcRenderer.invoke('agent:run', { tool, args, dryRun }),
    ai: (tool, args, opts) => ipcRenderer.invoke('agent:ai', { tool, args, ...(opts || {}) }),
    cancel: (id) => ipcRenderer.invoke('agent:cancel', { id }),
    answer: (id, a) => ipcRenderer.invoke('agent:answer', { id, ...(a || {}) }),
    get: (id) => ipcRenderer.invoke('agent:get', { id }),
    list: (limit) => ipcRenderer.invoke('agent:list', { limit }),
    audit: (limit) => ipcRenderer.invoke('agent:audit', { limit }),
    icon: (path) => ipcRenderer.invoke('desktop:icon', { path }),
    onEvent: on('agent:event')
  },
  win: (action) => ipcRenderer.send('win', action)
});

